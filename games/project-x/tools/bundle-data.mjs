// Bundles data/*.json into data.js so the game also runs from file:// (no fetch needed).
import fs from 'node:fs'; import path from 'node:path'; import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url)), root = path.join(here, '..'), d = path.join(root, 'data');
const rd = f => JSON.parse(fs.readFileSync(path.join(d, f), 'utf8'));
const maps = {};
for (const f of fs.readdirSync(path.join(d, 'maps'))) maps[f.replace('.json', '')] = rd('maps/' + f);
const out = { maps, tiles: rd('tiles.json'), props: rd('props.json'), world: rd('world.json'), items: rd('items.json'), recipes: rd('recipes.json'), attacks: rd('attacks.json'), zemantas: rd('zemantas.json') };
fs.writeFileSync(path.join(root, 'data.js'), '/* generated by tools/bundle-data.mjs from data/*.json */\nwindow.PX_DATA = ' + JSON.stringify(out) + ';\n');
console.log('data.js', Object.keys(maps).length, 'maps');
